def _run(argv: list[str]) -> str:
    result = subprocess.run(argv, capture_output=True, text=True, timeout=15, check=True)
    return result.stdout.strip()


def _xdg(name: str, default: str) -> Path:
    from setup_system.infrastructure.file_receipts import checked_directory

    return checked_directory(Path(os.environ.get(name, Path.home() / default)))


def _config() -> Path:
    return _xdg("XDG_CONFIG_HOME", ".config")


def _checked(path: Path) -> Path:
    return target_path(path.relative_to(Path.home().resolve()).as_posix())


def _hyprland_version() -> str | None:
    return installed_version("hyprland") if shutil.which("Hyprland") else None


def _required_commands(root: Path) -> None:
    """Fail before user writes if the system stage did not deliver the configured tools."""
    commands = load_policy(root).hyprland.commands
    missing = [name for name in commands if shutil.which(name) is None]
    agent = Path("/usr/libexec/hyprpolkitagent")
    if not agent.is_file() or not os.access(agent, os.X_OK):
        missing.append(str(agent))
    if missing:
        raise ValueError("Hyprland system stage is incomplete; missing: " + ", ".join(missing))


def _hypr_files(root: Path, names: tuple[str, ...]) -> dict[str, Path]:
    """Require the intended regular assets; generated source-tree files are not inputs."""
    folder = root / "assets/hyprland"
    if folder.is_symlink() or not folder.is_dir():
        raise ValueError("Hyprland profile source directory is missing or unsafe")
    sources = {name: folder / name for name in names}
    for name, path in sources.items():
        if path.is_symlink() or not path.is_file():
            raise ValueError(f"Hyprland profile requires a regular source asset: {name}")
    return sources


def theme_files(
    root: Path,
    *,
    theme: ThemeSettings | None = None,
    keyboard: str | None = None,
    monitors: tuple[MonitorLayout, ...] = (),
) -> dict[Path, bytes]:
    """Return the selected visual resources without touching session startup."""
    policy = font_policy(root)
    target = _config() / "hypr/setup-system"
    return {
        _checked(target / name): policy.render(source, theme, keyboard=keyboard, monitors=monitors)
        for name, source in _hypr_files(root, THEMED_ASSETS).items()
    }


def desktop_files(
    root: Path,
    *,
    theme: ThemeSettings | None = None,
    keyboard: str | None = None,
    monitors: tuple[MonitorLayout, ...] = (),
) -> dict[Path, bytes]:
    config = _config()
    policy = font_policy(root)
    fontconfig = _checked(config / "fontconfig/conf.d/60-setup-system-fonts.conf")
    font_content = policy.render(root / "assets/fonts/60-setup-system-fonts.conf")
    sources = _hypr_files(root, HYPRLAND_ASSETS)
    targets = {
        config / "hypr/setup-system" / name: policy.render(
            path, theme, keyboard=keyboard, monitors=monitors
        )
        for name, path in sources.items()
        if name != "start-hyprland"
    }
    entry = _checked(config / "hypr/hyprland.lua")
    original = entry.read_text() if entry.exists() else ""
    line = 'require("setup-system.profile")'
    if original.strip() and line not in original.splitlines():
        raise ValueError("Existing Hyprland entrypoint requires a reviewed manual include")
    targets[entry] = (
        "-- Managed by setupSystem; put personal overrides in local.lua.\n"
        + line
        + "\n"
        + 'local cfg = os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")\n'
        + 'local path = cfg .. "/hypr/local.lua"\n'
        + 'local source = io.open(path, "r")\n'
        + "if source then source:close(); dofile(path) end\n"
    ).encode()
    targets[fontconfig] = font_content
    targets[config / "xdg-desktop-portal/hyprland-portals.conf"] = (
        b"[preferred]\ndefault=hyprland;gtk\norg.freedesktop.impl.portal.FileChooser=gtk\n"
    )
    gtk = (
        "# Managed by setupSystem\n[Settings]\ngtk-theme-name=Adwaita-dark\n"
        "gtk-icon-theme-name=Adwaita\ngtk-cursor-theme-name=Adwaita\n"
        f"gtk-font-name={policy.family} {policy.ui_size}\n"
        "gtk-application-prefer-dark-theme=1\n"
    ).encode()
    targets[config / "gtk-3.0/settings.ini"] = gtk
    targets[config / "gtk-4.0/settings.ini"] = gtk
    data = _xdg("XDG_DATA_HOME", ".local/share")
    source = sources["start-hyprland"].read_text()
    for placeholder, path in (
        ("CONFIG_HOME", config),
        ("DATA_HOME", data),
        ("STATE_HOME", _xdg("XDG_STATE_HOME", ".local/state")),
        ("CACHE_HOME", _xdg("XDG_CACHE_HOME", ".cache")),
    ):
        source = source.replace("@" + placeholder + "@", shlex.quote(str(path)))
    targets[data / "setup-system/bin/start-hyprland"] = source.encode()
    return {_checked(path): content for path, content in targets.items()}


def desktop_drift(
    root: Path,
    *,
    theme: ThemeSettings | None = None,
    keyboard: str | None = None,
    monitors: tuple[MonitorLayout, ...] = (),
) -> tuple[Path, ...]:
    desired = desktop_files(root, theme=theme, keyboard=keyboard, monitors=monitors)
    launcher = _xdg("XDG_DATA_HOME", ".local/share") / "setup-system/bin/start-hyprland"
    return (*changed_files(desired, modes={launcher: 0o700}), *font_drift(root))


def plan_fonts(root: Path) -> str:
    policy = font_policy(root)
    lines = [f"Primary font: {policy.family}", f"Emoji fallback: {policy.emoji_fallback}"]
    if shutil.which("fc-match"):
        for query in ("monospace", policy.family, policy.emoji_fallback):
            observed = _run(["fc-match", "-f", "%{family}: %{style}", query])
            lines.append(f"{query} currently matches {observed}")
    target = _checked(_config() / "fontconfig/conf.d/60-setup-system-fonts.conf")
    alias = policy.render(root / "assets/fonts/60-setup-system-fonts.conf")
    current = observe(target)
    expected = (
        {target: current.sha256}
        if current and current.sha256 in policy.previous_fontconfig_sha256
        else {}
    )
    changes = (*changed_files({target: alias}, expected=expected), *font_drift(root))
    lines.extend(f"Would update {path}" for path in changes)
    if not changes:
        lines.append("Font files already match the selected profile.")
    return "\n".join(lines)


def apply_fonts(root: Path, *, offline: bool = False) -> Path:
    if os.geteuid() == 0:
        raise ValueError("User fonts cannot run as root")
    policy = font_policy(root)
    if policy.emoji_fallback not in _run(["fc-match", "-f", "%{family}", policy.emoji_fallback]):
        raise ValueError("Install the selected emoji fallback before applying fonts")
    target = _checked(_config() / "fontconfig/conf.d/60-setup-system-fonts.conf")
    desired = font_files(root, offline=offline)
    refresh_cache = bool(desired)
    desired[target] = policy.render(root / "assets/fonts/60-setup-system-fonts.conf")
    before = observe(target)
    expected = (
        {target: before.sha256}
        if before and before.sha256 in policy.previous_fontconfig_sha256
        else {}
    )
    folder = apply_files(desired, expected=expected)
    if refresh_cache:
        _run(["fc-cache", str(_xdg("XDG_DATA_HOME", ".local/share") / "fonts")])
    return folder


def apply_desktop(
    root: Path,
    *,
    theme: ThemeSettings | None = None,
    keyboard: str | None = None,
    monitors: tuple[MonitorLayout, ...] = (),
    offline: bool = False,
) -> Path:
    if os.geteuid() == 0:
        raise ValueError("Hyprland user configuration cannot run as root")
    # Validate Debian release, architecture and the installed backend before any download.
    package_arguments(root=root)
    expected_version = load_policy(root).hyprland.upstream_version
    version = _hyprland_version()
    if (
        version is None
        or re.search(r"(?<![0-9.])" + re.escape(expected_version) + r"(?![0-9.])", version) is None
    ):
        raise ValueError(f"Hyprland {expected_version} must be installed in Textual Base system")
    _required_commands(root)
    desired = desktop_files(root, theme=theme, keyboard=keyboard, monitors=monitors)
    fonts = font_files(root, offline=offline)
    refresh_cache = bool(fonts)
    desired.update(fonts)
    launcher = _xdg("XDG_DATA_HOME", ".local/share") / "setup-system/bin/start-hyprland"
    folder = apply_files(desired, modes={launcher: 0o700})
    if refresh_cache:
        _run(["fc-cache", str(_xdg("XDG_DATA_HOME", ".local/share") / "fonts")])
    return folder
